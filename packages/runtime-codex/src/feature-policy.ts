export const KEPT_FEATURES: readonly string[] = Object.entries(FEATURE_POLICY)
  .filter(([, ruling]) => ruling === "keep")
  .map(([name]) => name);

/**
 * The `features` table for a `thread/start` `config`: every feature not kept, set to false. Keys
 * are whole feature names, dots included (`guardianv2.thread_context`); Codex reads each key under
 * `features` as one name, where a flat dotted `features.a.b` key would be read as a nested table.
 */
export function featureDisableConfig(
  policy: Readonly<Record<string, FeatureRuling>> = FEATURE_POLICY,
): Record<string, false> {
  const config: Record<string, false> = {};
  for (const [name, ruling] of Object.entries(policy))
    if (ruling === "disable") config[name] = false;
  return config;
}
